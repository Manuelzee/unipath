import { Router, type IRouter, type Request, type Response } from "express";
import { getAuth } from "../lib/auth/session";
import { and, desc, eq } from "drizzle-orm";
import {
  AskAiAssistantBody, AskAiAssistantResponse, DeleteAiSavedItemParams, GetAiStatusResponse,
  ListAiSavedItemsResponse, ReviewEssayBody, ReviewEssayResponse, SaveAiItemBody, SaveAiItemResponse,
} from "@workspace/api-zod";
import { aiSavedItemsTable, db, type AiSavedItemRecord } from "@workspace/db";
import { requireAuth } from "../middlewares/requireAuth";
import { requireJson } from "../middlewares/requireJson";
import { AI_DISCLAIMER, AI_PROVIDER_NAME, aiConfig, type AiConfig } from "../lib/ai/config";
import { loadGrounding } from "../lib/ai/context";
import { SHARED_PROFILE_FIELDS, type GroundingFact } from "../lib/ai/grounding";
import { buildChatMessages, buildEssayMessages, type ProviderMessage } from "../lib/ai/prompts";
import { AiProviderError, complete } from "../lib/ai/provider";
import { BurstLimiter } from "../lib/ai/burst";
import { providerUserRef, recordUsage, usageToday } from "../lib/ai/quota";
import { safeWebUrl } from "../lib/applicationHelpers";

const router: IRouter = Router();
const burst = new BurstLimiter(6, 60_000);

function studentId(req: Request): string {
  const userId = getAuth(req).userId;
  if (!userId) throw new Error("Authenticated user ID was not available.");
  return userId;
}

type AiErrorCode = "AI_NOT_CONFIGURED" | "AI_DAILY_LIMIT" | "AI_RATE_LIMITED" | "AI_PROVIDER_ERROR" | "AI_INVALID_INPUT";
const fail = (res: Response, status: number, code: AiErrorCode, error: string) => { res.status(status).json({ code, error }); };

router.get("/ai/status", requireAuth, async (req, res): Promise<void> => {
  const config = aiConfig();
  const usage = await usageToday(studentId(req));
  res.setHeader("Cache-Control", "private, no-store");
  res.json(GetAiStatusResponse.parse({
    configured: !!config, provider: AI_PROVIDER_NAME, model: config?.model ?? null,
    plan: usage.plan, dailyLimit: usage.dailyLimit, usedToday: usage.usedToday, remainingToday: usage.remainingToday,
    profileFieldsShared: [...SHARED_PROFILE_FIELDS],
    notice: config
      ? "Answers are generated by an AI model from your profile and the UniPath records you select. They are suggestions to review, not official advice."
      : "The AI assistant is not connected yet. The site owner needs to add an AI provider key on the server. Nothing you type is sent anywhere until then.",
  }));
});

/** Shared request gate: configuration, burst limit and daily quota, in that order. */
async function gate(req: Request, res: Response): Promise<{ config: AiConfig; userId: string } | null> {
  const config = aiConfig();
  if (!config) { fail(res, 503, "AI_NOT_CONFIGURED", "The AI assistant is not connected yet. Nothing was sent."); return null; }
  const userId = studentId(req);
  if (!burst.take(userId)) { fail(res, 429, "AI_RATE_LIMITED", "Too many requests in a short time. Wait a minute and try again."); return null; }
  const usage = await usageToday(userId);
  if (usage.remainingToday <= 0) {
    fail(res, 429, "AI_DAILY_LIMIT", `You have used all ${usage.dailyLimit} AI requests for today. Your limit resets at 00:00 UTC.`);
    return null;
  }
  return { config, userId };
}

async function run(res: Response, ctx: { config: AiConfig; userId: string }, kind: "chat" | "essay_review",
  messages: ProviderMessage[], maxTokens: number, grounding: GroundingFact[]) {
  try {
    const result = await complete(ctx.config, messages, maxTokens, providerUserRef(ctx.userId));
    await recordUsage(ctx.userId, kind, "ok", result);
    const usage = await usageToday(ctx.userId);
    res.setHeader("Cache-Control", "private, no-store");
    return {
      reply: result.text, grounding, model: result.model, disclaimer: AI_DISCLAIMER, generatedAt: new Date().toISOString(),
      usage: { dailyLimit: usage.dailyLimit, usedToday: usage.usedToday, remainingToday: usage.remainingToday },
    };
  } catch (error) {
    if (!(error instanceof AiProviderError)) throw error;
    // Provider failures are logged for monitoring but never count against the student's quota.
    await recordUsage(ctx.userId, kind, "provider_error").catch(() => undefined);
    res.req.log.warn({ reason: error.reason, upstreamStatus: error.upstreamStatus }, "AI provider request failed");
    fail(res, 502, "AI_PROVIDER_ERROR", error.reason === "timeout"
      ? "The AI provider took too long to respond. Please try again. Nothing was saved."
      : "The AI provider could not complete this request. Please try again later. Nothing was saved.");
    return null;
  }
}

router.post("/ai/chat", requireAuth, requireJson, async (req, res): Promise<void> => {
  const body = AskAiAssistantBody.safeParse(req.body);
  if (!body.success) { fail(res, 400, "AI_INVALID_INPUT", "Write a question of up to 2,000 characters and choose at most three universities."); return; }
  const ctx = await gate(req, res);
  if (!ctx) return;
  const { facts } = await loadGrounding(ctx.userId, {
    useProfile: body.data.useProfile ?? true, universityIds: body.data.universityIds ?? [],
  });
  const result = await run(res, ctx, "chat", buildChatMessages(body.data.message, body.data.history ?? [], facts), 900, facts);
  if (result) res.json(AskAiAssistantResponse.parse(result));
});

router.post("/ai/essay-review", requireAuth, requireJson, async (req, res): Promise<void> => {
  const body = ReviewEssayBody.safeParse(req.body);
  if (!body.success) { fail(res, 400, "AI_INVALID_INPUT", "Paste an essay between 50 and 12,000 characters. The prompt can be up to 1,000 characters."); return; }
  const ctx = await gate(req, res);
  if (!ctx) return;
  // Essay feedback needs only the target school, not the student's academic profile.
  const { facts } = await loadGrounding(ctx.userId, {
    useProfile: false, universityIds: body.data.universityId ? [body.data.universityId] : [],
  });
  const result = await run(res, ctx, "essay_review", buildEssayMessages(body.data, facts), 1400, facts);
  if (result) res.json(ReviewEssayResponse.parse(result));
});

const toItem = (row: AiSavedItemRecord) => ({ ...row, createdAt: row.createdAt.toISOString() });

router.get("/me/ai/saved", requireAuth, async (req, res): Promise<void> => {
  const rows = await db.select().from(aiSavedItemsTable)
    .where(eq(aiSavedItemsTable.userId, studentId(req))).orderBy(desc(aiSavedItemsTable.createdAt));
  res.setHeader("Cache-Control", "private, no-store");
  res.json(ListAiSavedItemsResponse.parse(rows.map(toItem)));
});

router.post("/me/ai/saved", requireAuth, requireJson, async (req, res): Promise<void> => {
  const body = SaveAiItemBody.safeParse(req.body);
  if (!body.success) { res.status(400).json({ error: "Add a title and some content before saving." }); return; }
  const userId = studentId(req);
  const sourceUrls = [...new Set((body.data.sourceUrls ?? []).map(u => safeWebUrl(u)).filter((u): u is string => !!u))];
  const [row] = await db.insert(aiSavedItemsTable).values({
    userId, kind: body.data.kind, title: body.data.title.trim(), content: body.data.content.trim(), sourceUrls,
  }).returning();
  res.status(201).json(SaveAiItemResponse.parse(toItem(row)));
});

router.delete("/me/ai/saved/:id", requireAuth, async (req, res): Promise<void> => {
  const params = DeleteAiSavedItemParams.safeParse(req.params);
  if (!params.success) { res.status(400).json({ error: "Invalid item." }); return; }
  const [row] = await db.delete(aiSavedItemsTable)
    .where(and(eq(aiSavedItemsTable.id, params.data.id), eq(aiSavedItemsTable.userId, studentId(req)))).returning();
  if (!row) { res.status(404).json({ error: "Item not found." }); return; }
  res.sendStatus(204);
});

export default router;
